//diff conversion and operation
console.log("1" + 2); // "12" (number to string)
console.log(1 + "2"); // "12" (number to string)
console.log("1" + 2 + 3); // "123" (left to right conversion: "1"+ 2 = "12", then "12" + 3 = "123")
console.log(1 + 2 + "3"); // "33" (left to right conversion: 1 + 2 = 3, then 3 + "3" = "33")

